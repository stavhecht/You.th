"""Seed ``evidwell_test`` for the browser tests (``frontend/e2e``).

Run by Playwright's global setup before every browser run:

    python -m tests.e2e.browser_seed

Empties the test database (refusing any database not named ``*_test``), then
writes what the browser tests read: a reviewer, three published articles, and
two drafts pending review — generated by the real orchestrator with the outside
world faked, so they carry sources and a clean validation report exactly like a
real draft (the desk will not publish a draft without sources).
"""

from __future__ import annotations

import asyncio
import uuid
from datetime import UTC, datetime

import sqlalchemy as sa
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.pool import NullPool

from app.config import get_settings
from app.domain.enums import RunOrigin, RunStatus, Verdict
from app.domain.models import PipelineRun
from app.pipeline.orchestrator import PipelineOrchestrator
from app.security.auth import hash_password
from tests.e2e.support import (
    E2E_URL,
    FakeExtraction,
    FakeProvider,
    build_stages,
    paper,
    seed_published,
)

#: Read by frontend/e2e/fixtures.ts. Test-only credentials for a test-only database.
REVIEWER_EMAIL = "reviewer@e2e.test"
REVIEWER_PASSWORD = "Reviewer-password-1"

PUBLISHED = [
    ("Creatine reliably adds strength", Verdict.SUPPORTED, "supplements"),
    ("Foam rolling before exercise", Verdict.WEAK, "fitness"),
    ("Cold showers and immunity", Verdict.NO_EVIDENCE, None),
]
#: (topic, product, ingredient) — one draft to approve, one to reject, one for
#: two reviewers editing at once.
DRAFTS = [
    ("Magnesium for sleep", "Magnesium glycinate", "magnesium"),
    ("Ashwagandha for stress", "Ashwagandha root extract", "ashwagandha"),
    ("Rhodiola for fatigue", "Rhodiola rosea", "rhodiola"),
]


async def _draft(
    factory: async_sessionmaker[AsyncSession],
    topic: str,
    product: str,
    ingredient: str,
    offset: int,
) -> None:
    async with factory() as db:
        run = PipelineRun(
            topic=topic,
            status=RunStatus.RUNNING,
            origin=RunOrigin.CONSOLE,
            attempts=1,
            created_at=datetime.now(UTC),
            started_at=datetime.now(UTC),
        )
        db.add(run)
        await db.commit()
        provider = FakeProvider([paper(offset + n, subject=ingredient) for n in range(1, 4)])
        stages = build_stages(
            db,
            provider=provider,
            extraction=FakeExtraction(product=product, ingredients=(ingredient,)),
        )
        orchestrator = PipelineOrchestrator(
            db, stages, factory, get_settings().pipeline_max_attempts
        )
        await orchestrator.run(run.id, topic, None, 1)


async def main() -> None:
    engine = create_async_engine(E2E_URL, poolclass=NullPool)
    async with engine.begin() as connection:
        name = await connection.scalar(sa.text("SELECT current_database()"))
        if not name.endswith("_test"):
            raise SystemExit(f"refusing to seed {name!r}: not a *_test database")
        tables = (
            (
                await connection.execute(
                    sa.text(
                        "SELECT tablename FROM pg_tables WHERE schemaname = 'public' "
                        "AND tablename <> 'schema_migrations'"
                    )
                )
            )
            .scalars()
            .all()
        )
        await connection.execute(
            sa.text(f"TRUNCATE {', '.join(tables)} RESTART IDENTITY CASCADE")
        )

    factory = async_sessionmaker(engine, expire_on_commit=False, class_=AsyncSession)
    reviewer_id = str(uuid.uuid4())
    async with factory() as db:
        await db.execute(
            sa.text(
                "INSERT INTO users (id, email, password_hash, display_name, role, created_at)"
                " VALUES (:id, :email, :hash, 'Browser Reviewer', 'reviewer', now())"
            ),
            {
                "id": reviewer_id,
                "email": REVIEWER_EMAIL,
                "hash": hash_password(REVIEWER_PASSWORD),
            },
        )
        await db.commit()

    for headline, verdict, subject in PUBLISHED:
        await seed_published(
            factory, reviewer_id, headline=headline, verdict=verdict, subject=subject
        )
    for index, (topic, product, ingredient) in enumerate(DRAFTS):
        await _draft(factory, topic, product, ingredient, offset=index * 10)

    async with factory() as db:
        counts = (
            await db.execute(
                sa.text("SELECT status, count(*) FROM articles GROUP BY status ORDER BY status")
            )
        ).all()
    await engine.dispose()
    print("seeded evidwell_test:", dict(counts))
    if dict(counts) != {"pending_review": len(DRAFTS), "published": len(PUBLISHED)}:
        raise SystemExit("seed did not produce the expected articles")


if __name__ == "__main__":
    asyncio.run(main())
